const router = require('express').Router();
const controller = require('../controllers/auth.controller');
const validate = require('../middleware/validate');
const { authenticate } = require('../middleware/auth');
const rateLimit = require('express-rate-limit');
const { registerDto, loginDto, emailDto, signupOtpRequestDto, otpVerifyDto, passwordResetVerifyDto, googleCredentialDto } = require('../dto/auth.dto');
const { profileDto } = require('../dto/customer.dto');
const otpLimiter = rateLimit({ windowMs: 15 * 60 * 1000, limit: 8, standardHeaders: true, legacyHeaders: false, message: { message: 'Too many verification attempts. Please wait and try again.' } });
router.post('/register', validate(registerDto), controller.register);
router.post('/login', validate(loginDto), controller.login);
router.post('/google', validate(googleCredentialDto), controller.google);
router.post('/otp/signup/request', otpLimiter, validate(signupOtpRequestDto), controller.requestSignupOtp);
router.post('/otp/signup/verify', otpLimiter, validate(otpVerifyDto), controller.verifySignupOtp);
router.post('/otp/login/request', otpLimiter, validate(emailDto), controller.requestLoginOtp);
router.post('/otp/login/verify', otpLimiter, validate(otpVerifyDto), controller.verifyLoginOtp);
router.post('/otp/password-reset/request', otpLimiter, validate(emailDto), controller.requestPasswordResetOtp);
router.post('/otp/password-reset/verify', otpLimiter, validate(passwordResetVerifyDto), controller.resetPassword);
router.get('/me', authenticate, controller.me);
router.patch('/me', authenticate, validate(profileDto), controller.updateMe);
module.exports = router;
